#!/usr/bin/env python3
"""Clear test-generated artifacts (storage files + database rows).

Keeps reference data (offline Ensembl reference, proteomes, self-filter index,
IEDC/MS evidence, trained models, reference caches). Intended to be run with
the platform STOPPED.

Usage:
    python scripts/clear_test_data.py --yes
"""
from __future__ import annotations

import argparse
import os
import shutil
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STORAGE = ROOT / "backend" / "storage"

# Test-generated storage directories to remove (everything generated by runs,
# uploads, jobs, demos and caches). Reference data is intentionally NOT listed.
TEST_DIRS = [
    "uploads",             # uploaded tumour/normal VCFs
    "jobs",                # one-click job temp uploads
    "synthetic",           # generated synthetic datasets
    "synthetic_integration",
    "one_click_demo",
    "project_files",       # registered files
    "validation_gold",     # generated validation gold dataset
    "vep_cache",           # annotation response cache
    "evidence_cache",      # gnomAD response cache
]

# Reference assets that MUST be preserved.
KEEP_DIRS = [
    "reference",
    "proteomes",
    "self_filter",
    "evidence",
    "models",
    "ensembl_cache",
]


def db_path() -> Path:
    url = os.environ.get("DATABASE_URL", "")
    if url.startswith("sqlite"):
        raw = url.split("///", 1)[-1]
        candidate = Path(raw)
        if not candidate.is_absolute():
            candidate = (ROOT / "backend" / candidate).resolve()
        return candidate
    return ROOT / "backend" / "neoantigen.db"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--yes", action="store_true", help="confirm destructive cleanup")
    parser.add_argument("--keep-files", action="store_true", help="only clear the database")
    args = parser.parse_args()
    if not args.yes:
        print("refusing to run without --yes", file=sys.stderr)
        return 1

    # 1) storage files
    if not args.keep_files:
        print("== clearing test storage directories ==")
        for name in TEST_DIRS:
            target = STORAGE / name
            if target.exists():
                size = sum(f.stat().st_size for f in target.rglob("*") if f.is_file())
                shutil.rmtree(target, ignore_errors=True)
                print(f"  removed {name}/ ({size / 1e6:.1f} MB)")
            else:
                print(f"  (absent) {name}/")
        print("  preserved:", ", ".join(d for d in KEEP_DIRS if (STORAGE / d).exists()))

    # 2) database rows
    path = db_path()
    if not path.is_file():
        print(f"database not found: {path}", file=sys.stderr)
        return 1
    before = path.stat().st_size
    con = sqlite3.connect(str(path), timeout=60)
    try:
        tables = [
            r[0]
            for r in con.execute(
                "SELECT name FROM sqlite_master WHERE type='table' "
                "AND name NOT LIKE 'sqlite_%' AND name != 'alembic_version'"
            )
        ]
        con.execute("PRAGMA foreign_keys=OFF")
        print("== clearing database tables ==")
        for name in tables:
            count = con.execute(f'SELECT COUNT(*) FROM "{name}"').fetchone()[0]
            if count:
                con.execute(f'DELETE FROM "{name}"')
                print(f"  {name}: -{count} rows")
        con.commit()
        con.execute("VACUUM")
        con.execute("PRAGMA wal_checkpoint(TRUNCATE)")
        print("  vacuum + wal checkpoint done")
    finally:
        con.close()
    after = path.stat().st_size
    print(f"database size: {before / 1e9:.2f} GB -> {after / 1e9:.2f} GB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
