import { extraEn, extraZh } from "@/lib/i18n.dict";
import {
  extraDe as pagesDe,
  extraFr as pagesFr,
  extraRu as pagesRu,
} from "@/lib/i18n.langs";
import {
  extraDe as dictDe,
  extraFr as dictFr,
  extraRu as dictRu,
} from "@/lib/i18n.dict.langs";
import * as pagesA from "@/lib/i18n.pages.a";
import * as pagesB from "@/lib/i18n.pages.b";
import * as pagesC from "@/lib/i18n.pages.c";
import * as pagesD from "@/lib/i18n.pages.dd";
import * as pagesE from "@/lib/i18n.pages.e";

const DICTS: Record<Lang, Dict> = {
  zh: {
    ...zh,
    ...extraZh,
    ...pagesA.extraZh,
    ...pagesB.extraZh,
    ...pagesC.extraZh,
    ...pagesD.extraZh,
    ...pagesE.extraZh,
  },
  en: {
    ...en,
    ...extraEn,
    ...pagesA.extraEn,
    ...pagesB.extraEn,
    ...pagesC.extraEn,
    ...pagesD.extraEn,
    ...pagesE.extraEn,
  },
  // English is the base for other languages, so any untranslated key shows
  // English rather than falling back to Chinese.
  ru: { ...en, ...ru, ...dictRu, ...pagesRu },
  fr: { ...en, ...fr, ...dictFr, ...pagesFr },
  de: { ...en, ...de, ...dictDe, ...pagesDe },
};

const LANG_CODES: Record<Lang, string> = {
  en: "en",
  zh: "zh-CN",
  ru: "ru",
  fr: "fr",
  de: "de",
};

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nValue>({
  lang: "en",
  setLang: () => undefined,
  t: (key) => key,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem("bravo.lang") as Lang | null;
    if (saved && LANG_CODES[saved]) {
      setLangState(saved);
      document.documentElement.lang = LANG_CODES[saved];
    } else {
      document.documentElement.lang = LANG_CODES.en;
    }
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    document.documentElement.lang = LANG_CODES[next];
    window.localStorage.setItem("bravo.lang", next);
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => {
      let value = DICTS[lang][key] ?? DICTS.en[key] ?? key;
      if (params) {
        for (const [name, replacement] of Object.entries(params)) {
          value = value.replace(new RegExp(`\\{${name}\\}`, "g"), String(replacement));
        }
      }
      return value;
    },
    [lang]
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
