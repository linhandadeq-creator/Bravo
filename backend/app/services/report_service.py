MEDIA_TYPES = {
    "json": "application/json",
    "markdown": "text/markdown",
    "html": "text/html",
    "csv": "text/csv",
    "pdf": "application/pdf",
}

EXTENSIONS = {"json": "json", "markdown": "md", "html": "html", "csv": "csv", "pdf": "pdf"}


def render_report(data: dict, fmt: str) -> tuple[str | bytes, str, str]:
    if fmt not in SUPPORTED_FORMATS:
        raise ReportError(f"Unsupported report format '{fmt}'")
    if fmt == "json":
        content: str | bytes = to_json(data)
    elif fmt == "markdown":
        content = to_markdown(data)
    elif fmt == "html":
        content = to_html(data)
    elif fmt == "pdf":
        content = to_pdf(data)
    else:
        content = to_csv(data)
    filename = f"report_{data['analysis_run']['id'][:8]}.{EXTENSIONS[fmt]}"
    return content, MEDIA_TYPES[fmt], filename


def build_report(db: Session, run: AnalysisRun, fmt: str) -> tuple[str, str, str]:
    data = collect_report_data(db, run)
    return render_report(data, fmt)


def report_summary(data: dict) -> dict:
    return {
        "analysis_run_id": data["analysis_run"]["id"],
        "run_status": data["analysis_run"]["status"],
        "reference_build": data["analysis_run"]["reference_build"],
        "raw_variants": (data.get("qc") or {}).get("raw_variants"),
        "valid_variants": (data.get("qc") or {}).get("valid_variants"),
        "somatic": data.get("somatic"),
        "annotation_count": len(data.get("annotations", [])),
        "hla_count": len(data.get("hla", [])),
        "expression_count": len(data.get("expression", [])),
        "candidate_count": len(data.get("neoantigen_candidates", [])),
        "construct_count": len(data.get("constructs", [])),
        "validation_status": (data.get("validation") or {}).get("status"),
    }
