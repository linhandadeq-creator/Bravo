DISCLAIMER = (
    "This report is generated by the Bravo research computing and simulation platform, "
    "for research use only. Predictions, ranking scores and production simulations are "
    "based on synthetic/simulated data and do not represent clinical, patient-response "
    "or therapeutic efficacy. Not for clinical decision-making or human use."
)

SUPPORTED_FORMATS = ("json", "markdown", "html", "csv", "pdf")

# Detailed per-row tables are capped so reports (and PDF generation) stay
# bounded for whole-genome runs with hundreds of thousands of variants.
# Aggregate/summary counts always reflect the full dataset.
MAX_REPORT_ROWS = 1000


class ReportError(RuntimeError):
    pass


def _count(db: Session, model, *criteria) -> int:
    return int(
        db.execute(select(func.count()).select_from(model).where(*criteria)).scalar() or 0
    )


def _latest_predictions(db: Session, run_id: str) -> dict[str, PredictionResult]:
    rows = list(
        db.execute(
            select(PredictionResult)
            .where(PredictionResult.analysis_run_id == run_id)
            .order_by(PredictionResult.created_at.desc())
        )
        .scalars()
        .all()
    )
    latest: dict[str, PredictionResult] = {}
    for row in rows:
        latest.setdefault(row.candidate_id, row)
    return latest


def collect_report_data(db: Session, run: AnalysisRun) -> dict:
    project = db.get(Project, run.project_id)
    qc = run.qc_summary or {}
    somatic = run.somatic_summary or {}

    somatic_rows = list(
        db.execute(
            select(SomaticCandidate)
            .where(SomaticCandidate.analysis_run_id == run.id)
            .order_by(SomaticCandidate.chromosome, SomaticCandidate.position)
            .limit(MAX_REPORT_ROWS)
        )
        .scalars()
        .all()
    )
    somatic_total = sum(int(v) for v in somatic.values() if isinstance(v, int))

    variants = {
        v.id: v
        for v in db.execute(
            select(Variant).where(
                Variant.analysis_run_id == run.id,
                Variant.sample_role == "TUMOR",
                Variant.is_valid.is_(True),
                Variant.is_duplicate.is_(False),
            )
        )
        .scalars()
        .all()
    }
    annotation_run = latest_annotation_run(db, run.id)
    annotations = []
    annotations_total = 0
    if annotation_run is not None:
        annotations_total = _count(
            db, VariantAnnotation, VariantAnnotation.annotation_run_id == annotation_run.id
        )
        for annotation in db.execute(
            select(VariantAnnotation)
            .where(VariantAnnotation.annotation_run_id == annotation_run.id)
            .order_by(VariantAnnotation.created_at)
            .limit(MAX_REPORT_ROWS)
        ).scalars().all():
            variant = variants.get(annotation.variant_id or "")
            if variant is None:
                continue
            annotations.append(
                {
                    "chromosome": variant.chromosome_normalized,
                    "position": variant.position,
                    "reference": variant.reference,
                    "alternate": variant.alternate,
                    "gene": annotation.gene,
                    "transcript": annotation.transcript,
                    "consequence": annotation.consequence,
                    "impact": annotation.impact,
                    "protein_change": annotation.protein_change,
                }
            )
    annotations.sort(key=lambda a: (str(a["chromosome"]), a["position"] or 0))

    hla = list(
        db.execute(
            select(HLAProfile)
            .where(HLAProfile.analysis_run_id == run.id)
            .order_by(HLAProfile.allele_class, HLAProfile.allele)
        )
        .scalars()
        .all()
    )
    expression_total = _count(
        db, ExpressionRecord, ExpressionRecord.analysis_run_id == run.id
    )
    expression = list(
        db.execute(
            select(ExpressionRecord)
            .where(ExpressionRecord.analysis_run_id == run.id)
            .order_by(ExpressionRecord.gene_symbol)
            .limit(MAX_REPORT_ROWS)
        )
        .scalars()
        .all()
    )

    candidates_total = _count(
        db, NeoantigenCandidate, NeoantigenCandidate.analysis_run_id == run.id
    )
    candidates = list(
        db.execute(
            select(NeoantigenCandidate)
            .where(NeoantigenCandidate.analysis_run_id == run.id)
            .order_by(NeoantigenCandidate.ranking_score.desc().nullslast())
            .limit(MAX_REPORT_ROWS)
        )
        .scalars()
        .all()
    )
    predictions = _latest_predictions(db, run.id)

    constructs = list_constructs(db, run.id)

    validation = (
        db.execute(
            select(ValidationReport)
            .order_by(ValidationReport.created_at.desc())
            .limit(1)
        )
        .scalars()
        .first()
    )

    annotation_run = latest_annotation_run(db, run.id)
    prediction_providers = [
        {"provider": p.provider, "version": p.provider_version}
        for p in {pred.provider: pred for pred in predictions.values()}.values()
    ]
    prediction_providers.sort(key=lambda item: item["provider"] or "")
    self_filter_available = is_available()
    methods = {
        "software_version": settings.APP_VERSION,
        "reference_build": run.reference_build,
        "annotation_provider": annotation_run.provider if annotation_run else None,
        "annotation_version": annotation_run.annotation_version if annotation_run else None,
        "transcript_source": annotation_run.transcript_source if annotation_run else None,
        "prediction_providers": prediction_providers,
        "self_filter_available": self_filter_available,
    }

    return {
        "title": f"Neoantigen Analysis Report · {project.name if project else run.project_id}",
        "software_version": settings.APP_VERSION,
        "disclaimer": DISCLAIMER,
        "methods": methods,
        "project": {
            "id": run.project_id,
            "name": project.name if project else None,
        },
        "analysis_run": {
            "id": run.id,
            "status": run.status,
            "mode": run.mode,
            "reference_build": run.reference_build,
            "created_at": run.created_at.isoformat() if run.created_at else None,
            "ranking_config": run.ranking_config,
        },
        "qc": qc,
        "somatic": somatic,
        "limits": {
            "max_rows": MAX_REPORT_ROWS,
            "somatic_candidates_total": somatic_total,
            "annotations_total": annotations_total,
            "expression_total": expression_total,
            "neoantigen_candidates_total": candidates_total,
            "truncated": any(
                total > MAX_REPORT_ROWS
                for total in (
                    somatic_total,
                    annotations_total,
                    expression_total,
                    candidates_total,
                )
            ),
        },
        "somatic_candidates": [
            {
                "chromosome": r.chromosome,
                "position": r.position,
                "reference": r.reference,
                "alternate": r.alternate,
                "classification": r.classification,
                "tumor_af": r.tumor_allele_frequency,
                "normal_af": r.normal_allele_frequency,
            }
            for r in somatic_rows
        ],
        "annotations": annotations,
        "hla": [
            {
                "allele": h.allele,
                "allele_class": h.allele_class,
                "locus": h.locus,
                "method": h.method,
                "confidence": h.confidence,
                "is_valid": h.is_valid,
                "is_duplicate": h.is_duplicate,
            }
            for h in hla
        ],
        "expression": [
            {
                "gene_symbol": e.gene_symbol,
                "gene_id": e.gene_id,
                "transcript_id": e.transcript_id,
                "level": e.level,
                "expression_value": e.expression_value,
                "unit": e.unit,
                "is_valid": e.is_valid,
            }
            for e in expression
        ],
        "neoantigen_candidates": [
            {
                "candidate_id": c.id,
                "gene": c.gene,
                "protein_change": c.protein_change,
                "consequence": c.consequence,
                "hla_allele": c.hla_allele,
                "hla_class": c.hla_class,
                "peptide_representation": c.peptide_representation,
                "prediction_status": c.prediction_status,
                "prediction_value": predictions[c.id].prediction_value
                if c.id in predictions
                else None,
                "metric_name": predictions[c.id].metric_name if c.id in predictions else None,
                "provider": predictions[c.id].provider if c.id in predictions else None,
                "ranking_score": c.ranking_score,
                "status": c.status,
            }
            for c in candidates
        ],
        "constructs": [
            {
                "id": c.id,
                "status": c.status,
                "simulation_format": c.simulation_format,
                "construct_representation": c.construct_representation,
                "candidate_ids": c.candidate_ids,
                "sequence_length": len(c.sequence or ""),
            }
            for c in constructs
        ],
        "validation": {
            "id": validation.id,
            "status": validation.status,
            "passed": validation.passed,
            "failed": validation.failed,
            "warnings": validation.warnings,
            "total_tests": validation.total_tests,
        }
        if validation
        else None,
    }


# ------------------------------------------------------------------ formats --
def to_json(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False)


def to_csv(data: dict) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(
        [
            "candidate_id",
            "gene",
            "protein_change",
            "consequence",
            "hla_allele",
            "prediction_status",
            "prediction_value",
            "ranking_score",
            "status",
        ]
    )
    for c in data["neoantigen_candidates"]:
        writer.writerow(
            [
                c["candidate_id"],
                c["gene"],
                c["protein_change"],
                c["consequence"],
                c["hla_allele"],
                c["prediction_status"],
                c["prediction_value"],
                c["ranking_score"],
                c["status"],
            ]
        )
    return buffer.getvalue()


def to_markdown(data: dict) -> str:
    run = data["analysis_run"]
    qc = data.get("qc") or {}
    lines = [
        f"# {data['title']}",
        "",
        f"> {data['disclaimer']}",
        "",
        "## Overview",
        "",
        f"- Project: {data['project']['name']}",
        f"- Analysis run: `{run['id']}`",
        f"- Status: {run['status']} · Mode: {run['mode']}",
        f"- Reference build: {run['reference_build']}",
        f"- Software version: {data['software_version']}",
        "",
        "## QC",
        "",
        f"- Raw variants: {qc.get('raw_variants', '—')}",
        f"- Valid variants: {qc.get('valid_variants', '—')}",
        f"- Invalid variants: {qc.get('invalid_variants', '—')}",
        f"- Duplicate variants: {qc.get('duplicate_variants', '—')}",
        f"- Chromosome normalized: {qc.get('chromosome_normalizations', '—')}",
        "",
        "## Tumour/normal classification",
        "",
        f"- Tumour-only: {data['somatic'].get('TUMOR_ONLY', 0)}",
        f"- Normal-only: {data['somatic'].get('NORMAL_ONLY', 0)}",
        f"- Shared: {data['somatic'].get('SHARED', 0)}",
        f"- Uncertain: {data['somatic'].get('UNCERTAIN', 0)}",
        "",
        "## Variant annotation",
        "",
        "| Locus | Change | Gene | Transcript | Consequence | Protein |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for a in data["annotations"]:
        lines.append(
            f"| {a['chromosome']}:{a['position']} | {a['reference']}>{a['alternate']} | "
            f"{a['gene'] or '—'} | {a['transcript'] or '—'} | {a['consequence'] or '—'} | "
            f"{a['protein_change'] or '—'} |"
        )

    lines += ["", "## HLA typing", "", "| Allele | Class | Method | Confidence | Valid |", "| --- | --- | --- | --- | --- |"]
    for h in data["hla"]:
        lines.append(
            f"| {h['allele'] or '—'} | {h['allele_class'] or '—'} | {h['method'] or '—'} | "
            f"{h['confidence'] if h['confidence'] is not None else '—'} | "
            f"{'yes' if h['is_valid'] else 'no'} |"
        )

    lines += ["", "## Expression", "", "| Gene | Transcript | Level | Expression | Unit |", "| --- | --- | --- | --- | --- |"]
    for e in data["expression"]:
        lines.append(
            f"| {e['gene_symbol'] or e['gene_id'] or '—'} | {e['transcript_id'] or '—'} | "
            f"{e['level']} | {e['expression_value'] if e['expression_value'] is not None else '—'} | "
            f"{e['unit'] or '—'} |"
        )

    lines += [
        "",
        "## Neoantigen candidates (ranked by research score)",
        "",
        "| Gene | Protein change | HLA | Prediction status | Predicted value | Research score | Candidate status |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for c in data["neoantigen_candidates"]:
        lines.append(
            f"| {c['gene'] or '—'} | {c['protein_change'] or '—'} | {c['hla_allele'] or '—'} | "
            f"{c['prediction_status']} | {c['prediction_value'] if c['prediction_value'] is not None else '—'} | "
            f"{c['ranking_score'] if c['ranking_score'] is not None else '—'} | {c['status']} |"
        )

    lines += ["", "## Construct simulation", ""]
    if data["constructs"]:
        for c in data["constructs"]:
            lines.append(f"- `{c['id'][:8]}` · Status {c['status']} · {c['simulation_format']}")
            lines.append(f"  - Representation：`{c['construct_representation'] or '—'}`")
            lines.append(f"  - Sequence length (simulated): {c['sequence_length']} nt")
    else:
        lines.append("- No construct record.")

    lines += ["", "## Validation"]
    if data["validation"]:
        v = data["validation"]
        lines.append(
            f"- Status: {v['status']} · pass {v['passed']}/{v['total_tests']} · fail {v['failed']} · warn {v['warnings']}"
        )
    else:
        lines.append("- No validation report yet.")

    methods = data.get("methods") or {}
    lines += ["", "## Methods & versions", ""]
    lines.append(f"- Software version: {methods.get('software_version')}")
    lines.append(f"- Reference build: {methods.get('reference_build')}")
    lines.append(
        f"- Annotation provider: {methods.get('annotation_provider')} "
        f"({methods.get('annotation_version')}) · transcript source {methods.get('transcript_source')}"
    )
    for provider in methods.get("prediction_providers", []):
        lines.append(f"- Prediction provider: {provider['provider']} {provider['version']}")
    lines.append(
        f"- Self-proteome off-target filter: {'enabled' if methods.get('self_filter_available') else 'not configured (explicitly flagged)'}"
    )
    limits = data.get("limits") or {}
    if limits.get("truncated"):
        lines.append(
            f"- Detailed tables limited to the first {limits.get('max_rows')} rows "
            f"(somatic candidates {limits.get('somatic_candidates_total')}, "
            f"annotations {limits.get('annotations_total')}, "
            f"expression {limits.get('expression_total')}, "
            f"neoantigen candidates {limits.get('neoantigen_candidates_total')}); "
            "aggregate counts cover the full dataset."
        )

    lines += ["", "---", "", data["disclaimer"], ""]
    return "\n".join(lines)


def to_html(data: dict) -> str:
    run = data["analysis_run"]
    qc = data.get("qc") or {}

    def esc(value) -> str:
        return html_lib.escape(str(value if value is not None else "—"))

    def table(headers: list[str], rows: list[list]) -> str:
        head = "".join(f"<th>{esc(h)}</th>" for h in headers)
        body = "".join(
            "<tr>" + "".join(f"<td>{esc(cell)}</td>" for cell in row) + "</tr>"
            for row in rows
        )
        return f'<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>'

    somatic = data["somatic"]
    sections = [
        f"<h1>{esc(data['title'])}</h1>",
        f'<p class="disclaimer">{esc(data["disclaimer"])}</p>',
        "<h2>Overview</h2>",
        '<div class="cards">'
        + "".join(
            f'<div class="card"><div class="k">{esc(k)}</div><div class="v">{esc(v)}</div></div>'
            for k, v in [
                ("Project", data["project"]["name"]),
                ("Analysis run", run["id"][:8]),
                ("Status", run["status"]),
                ("Mode", run["mode"]),
                ("Reference build", run["reference_build"]),
                ("Software version", data["software_version"]),
            ]
        )
        + "</div>",
        "<h2>QC</h2>",
        '<div class="cards">'
        + "".join(
            f'<div class="card"><div class="k">{esc(k)}</div><div class="v">{esc(v)}</div></div>'
            for k, v in [
                ("Raw variants", qc.get("raw_variants")),
                ("Valid variants", qc.get("valid_variants")),
                ("Invalid variants", qc.get("invalid_variants")),
                ("Duplicate variants", qc.get("duplicate_variants")),
            ]
        )
        + "</div>",
        "<h2>Tumour / normal classification</h2>",
        '<div class="cards">'
        + "".join(
            f'<div class="card"><div class="k">{esc(k)}</div><div class="v">{esc(somatic.get(key, 0))}</div></div>'
            for k, key in [
                ("Tumour-only", "TUMOR_ONLY"),
                ("Normal-only", "NORMAL_ONLY"),
                ("Shared", "SHARED"),
                ("Uncertain", "UNCERTAIN"),
            ]
        )
        + "</div>",
        "<h2>Variant annotation</h2>",
        table(
            ["Locus", "Change", "Gene", "Transcript", "Consequence", "Protein"],
            [
                [f"{a['chromosome']}:{a['position']}", f"{a['reference']}>{a['alternate']}", a["gene"], a["transcript"], a["consequence"], a["protein_change"]]
                for a in data["annotations"]
            ],
        ),
        "<h2>HLA typing</h2>",
        table(
            ["Allele", "Class", "Method", "Confidence", "Valid"],
            [[h["allele"], h["allele_class"], h["method"], h["confidence"], "yes" if h["is_valid"] else "no"] for h in data["hla"]],
        ),
        "<h2>Expression</h2>",
        table(
            ["Gene", "Transcript", "Level", "Expression", "Unit"],
            [[e["gene_symbol"] or e["gene_id"], e["transcript_id"], e["level"], e["expression_value"], e["unit"]] for e in data["expression"]],
        ),
        "<h2>Neoantigen candidates (ranked by research score)</h2>",
        table(
            ["Gene", "Protein change", "HLA", "Prediction status", "Predicted value", "Research score", "Candidate status"],
            [[c["gene"], c["protein_change"], c["hla_allele"], c["prediction_status"], c["prediction_value"], c["ranking_score"], c["status"]] for c in data["neoantigen_candidates"]],
        ),
        "<h2>Construct simulation</h2>",
        table(
            ["Construct", "Status", "Format", "Representation", "Sequence length (nt)"],
            [[c["id"][:8], c["status"], c["simulation_format"], c["construct_representation"], c["sequence_length"]] for c in data["constructs"]],
        )
        or "<p>No construct record.</p>",
        "<h2>Validation</h2>",
        (
            f'<p>Status {esc(data["validation"]["status"])} · pass '
            f'{esc(data["validation"]["passed"])}/{esc(data["validation"]["total_tests"])} · '
            f'fail {esc(data["validation"]["failed"])} · warn {esc(data["validation"]["warnings"])}</p>'
            if data["validation"]
            else "<p>No validation report yet.</p>"
        ),
        "<h2>Methods &amp; versions</h2>",
        (
            '<ul class="methods">'
            + "".join(
                f"<li>{esc(label)}：{esc(value)}</li>"
                for label, value in [
                    ("Software version", (data.get("methods") or {}).get("software_version")),
                    ("Reference build", (data.get("methods") or {}).get("reference_build")),
                    (
                        "Annotation provider",
                        f"{(data.get('methods') or {}).get('annotation_provider')} "
                        f"({(data.get('methods') or {}).get('annotation_version')})",
                    ),
                    (
                        "Prediction provider",
                        ", ".join(
                            f"{p['provider']} {p['version']}"
                            for p in (data.get("methods") or {}).get("prediction_providers", [])
                        )
                        or "—",
                    ),
                    (
                        "Self-proteome off-target filter",
                        "enabled"
                        if (data.get("methods") or {}).get("self_filter_available")
                        else "not configured",
                    ),
                ]
            )
            + (
                f'<li>{esc("Report scope")}：'
                f'Detailed tables limited to the first '
                f'{esc((data.get("limits") or {}).get("max_rows"))} rows; '
                f'aggregate counts cover the full dataset.</li>'
                if (data.get("limits") or {}).get("truncated")
                else ""
            )
            + "</ul>"
        ),
    ]
    body = "\n".join(sections)

    style = """
    :root { --fg:#1a1a1a; --muted:#6b7280; --line:#e5e7eb; --rule:#111827; }
    * { box-sizing:border-box; }
    body { margin:0; padding:48px 24px; background:#ffffff; color:var(--fg);
      font-family:-apple-system,BlinkMacSystemFont,"Segoe UI","PingFang SC","Helvetica Neue",Arial,sans-serif;
      font-size:14px; line-height:1.6; -webkit-font-smoothing:antialiased; }
    .sheet { max-width:880px; margin:0 auto; }
    h1 { font-size:22px; font-weight:600; letter-spacing:-.01em; margin:0 0 6px; }
    h2 { font-size:15px; font-weight:600; margin:32px 0 10px; padding-bottom:6px;
      border-bottom:1px solid var(--line); }
    .disclaimer { color:var(--muted); font-size:12px; line-height:1.7;
      border-left:2px solid var(--rule); padding-left:12px; margin:0 0 8px; }
    .cards { display:grid; grid-template-columns:repeat(4,1fr); gap:0;
      border:1px solid var(--line); border-radius:6px; overflow:hidden; }
    .card { padding:14px 16px; border-right:1px solid var(--line); }
    .card:last-child { border-right:none; }
    .k { color:var(--muted); font-size:11px; letter-spacing:.02em; }
    .v { font-size:19px; font-weight:600; margin-top:4px; font-variant-numeric:tabular-nums; }
    table { width:100%; border-collapse:collapse; font-size:12.5px; }
    th { text-align:left; color:var(--muted); font-weight:500; font-size:11px;
      letter-spacing:.02em; padding:7px 10px; border-bottom:1px solid var(--line); }
    td { padding:8px 10px; border-bottom:1px solid var(--line); }
    @media print { body { padding:0; } }
    """
    return (
        "<!doctype html><html lang='zh-CN'><head><meta charset='utf-8'>"
        f"<title>{html_lib.escape(data['title'])}</title><style>{style}</style></head>"
        f"<body><div class='sheet'>{body}</div></body></html>"
    )


_PDF_FONT = "STSong-Light"
_pdf_font_ready = False


def _ensure_pdf_font() -> None:
    global _pdf_font_ready
    if _pdf_font_ready:
        return
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.cidfonts import UnicodeCIDFont

    pdfmetrics.registerFont(UnicodeCIDFont(_PDF_FONT))
    _pdf_font_ready = True


def _esc(value) -> str:
    text = "" if value is None else str(value)
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


